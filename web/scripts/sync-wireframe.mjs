// Copies the wireframe editor (../../utils/wireframe) into this app: the editor bundle and its CSS for
// the "Edit screens" page, the thumbnail bundle (+ the .wf- rules of the CSS) for the design page, and
// the core bundle the server keeps screens with. Run after `deno task bundle && deno task bundle:embed` there.
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const src = resolve(process.env.WIREFRAME_DIR ?? "../../utils/wireframe");
const pub = resolve("public/wireframe");
copyFileSync(resolve(src, "dist/editor.js"), resolve(pub, "editor.js"));
copyFileSync(resolve(src, "dist/embed-thumb.js"), resolve(pub, "embed-thumb.js"));
copyFileSync(resolve(src, "src/editor/editor.css"), resolve(pub, "editor.css"));
copyFileSync(resolve(src, "dist/embed-core.js"), resolve("src/vendor/wireframe/core.js"));

// thumb.css: only the rules that draw parts (.wf-*), so the site's own styles stay untouched.
const css = readFileSync(resolve(src, "src/editor/editor.css"), "utf8");
const kept = [];
let depth = 0;
let start = 0;
for (let i = 0; i < css.length; i++) {
  const ch = css[i];
  if (ch === "{") {
    if (depth === 0) start = css.lastIndexOf("}", i) + 1;
    depth++;
  } else if (ch === "}") {
    depth--;
    if (depth === 0) {
      const rule = css.slice(start, i + 1).trim();
      const selector = rule.slice(0, rule.indexOf("{")).trim();
      if (selector.startsWith("@keyframes wf-") || selector === ":root") kept.push(rule);
      else if (!selector.startsWith("@") && selector.split(",").every((s) => s.includes(".wf-"))) kept.push(rule);
    }
  }
}
writeFileSync(resolve(pub, "thumb.css"), `/* Generated by scripts/sync-wireframe.mjs from the wireframe editor's CSS. */\n${kept.join("\n")}\n`);
console.log(`synced wireframe editor from ${src} (${kept.length} thumbnail rules)`);
